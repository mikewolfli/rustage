//! The preview service: its lifecycle, the session it owns, and the instances and process that must
//! all be gone once it is stopped (task T14.01).
//!
//! The acceptance line is *"after stopping there is no dangling instance or process"*. A dangling
//! thing is one nobody can reach any more, so the state machine is built so stopping cannot leave one:
//!
//! * **One session at a time.** [`Preview::start`] refuses a second session while one is live, so the
//!   service never owns two.
//! * **An instance has a generation, and a rebuild is a new one.** [`Preview::rebuild`] bumps the
//!   generation, so a handle made for the old instance cannot read the new one — the same rule the
//!   design scene uses.
//! * **Stopping clears everything.** [`Preview::stop`] takes the process and the instances away and
//!   answers what it released, and [`Preview::is_clean`] is the honest check that nothing is left.
//! * **A transition out of order is refused.** Ready before starting, stopping before running and
//!   finishing a stop that never began are each `Err`, so the lifecycle cannot be half-entered.
//!
//! # A mounted view is the session, not a counter
//!
//! [`Preview::mount_view`] mounts a [`Document`] through the library's declarative layer
//! (`ViewEngine::mount`), [`Preview::update_view`] applies the library's diff (`ViewEngine::update`),
//! and [`Preview::stop`] unregisters every control the session created before dropping the engine.
//! The unregistration is not decorative: `ViewEngine` has no `Drop` that tears its controls down, so
//! dropping the engine alone would leave them mounted in `widget::runtime` — exactly the dangling
//! instance the acceptance line forbids.
//!
//! Focus is captured through `widget::runtime::focused_widget` and restored through
//! `focus_widget`, keyed by the document's `NodeId`. Scroll has no generic accessor in the pinned
//! revision; [`state_keep::SCROLL_GAP`] is the exact gap and the preview reports it rather than
//! claiming a restore it cannot perform.
//!
//! # A classified edit is a decision, not a patch
//!
//! [`Preview::apply_update`] is the one door from a [`hot_update::Update`] to the live session, and
//! it answers with a [`Decision`] rather than a patch count:
//!
//! * **A live edit becomes a declaration rebuild.** A property, a style or an existing-binding edit
//!   is written into the [`Document`] model and the whole declaration is handed to
//!   `ViewEngine::update`. The library has no "apply this property patch" door — it rebuilds the
//!   declaration and diffs it — so [`Decision::Applied`] says exactly that and counts the diff's
//!   patches, not a promise of incremental work.
//! * **A rebuilding edit is a restart, not a patch.** An added/removed node, an added/removed
//!   binding and source text are [`Decision::RestartRequired`]. The diff *could* insert a node into
//!   the live tree, but this session's declaration is regenerated by cargo; patching the live tree
//!   would show a tree the next build cannot reproduce.
//! * **A live edit with no model slot is a no-op with a reason.** The classification is not the
//!   last word: an edit the document does not address is [`Decision::Noop`], so nothing is reported
//!   as applied merely because it was classified live.
//! * **A live edit the library refuses is also a restart.** A root-kind change is classified live by
//!   shape but cannot be expressed as a patch batch; the library's refusal is reported verbatim and
//!   the last good declaration stays mounted, so the engine remains usable.

#![allow(dead_code)]

