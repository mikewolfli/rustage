/// One node of a preview document.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct DocumentNode {
    /// The durable model identity. It is the node's key in the mounted tree.
    pub node: NodeId,
    /// The widget kind the node renders as.
    pub kind: String,
    /// The text property the node declares.
    ///
    /// It has its own field because it is the one property every preview document carries; every
    /// other property travels in [`Self::props`].
    pub text: String,
    /// Every other property the node declares, in name order.
    pub props: BTreeMap<String, String>,
}

impl DocumentNode {
    /// A node of a kind with some text.
    pub fn new(node: NodeId, kind: impl Into<String>, text: impl Into<String>) -> Self {
        Self {
            node,
            kind: kind.into(),
            text: text.into(),
            props: BTreeMap::new(),
        }
    }

    /// The same node with one more property.
    pub fn with_property(mut self, name: impl Into<String>, value: impl Into<String>) -> Self {
        self.set_property(name.into(), value.into());
        self
    }

    /// Sets one property, routing `text` to its own field so a node never declares it twice.
    ///
    /// Answers whether the node's declaration actually changed.
    fn set_property(&mut self, name: String, value: String) -> bool {
        if name == "text" {
            if self.text == value {
                return false;
            }
            self.text = value;
            self.props.remove("text");
            return true;
        }
        match self.props.get(&name) {
            Some(held) if *held == value => false,
            _ => {
                self.props.insert(name, value);
                true
            }
        }
    }
}

/// What applying one classified edit did to the document model.
#[derive(Clone, PartialEq, Eq, Debug)]
enum Application {
    /// The model now holds a different value.
    Changed,
    /// The model already held that value.
    Unchanged,
    /// The edit does not address a property this document models, and why.
    Unsupported(String),
}

/// The document a preview session mounts.
///
/// The root's kind is part of the document so a test can exercise the one change a patch batch
/// cannot express: replacing the root. Every child is keyed by its `NodeId`, which is what lets
/// [`Preview::capture_state`] map a live control back to the model and what keeps a control's
/// identity stable across an update.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Document {
    /// The root's widget kind.
    pub root: String,
    /// The root's children, in order.
    pub nodes: Vec<DocumentNode>,
}

impl Document {
    /// A document with an empty root of `root`.
    pub fn new(root: impl Into<String>) -> Self {
        Self {
            root: root.into(),
            nodes: Vec::new(),
        }
    }

    /// The same document with one more child.
    pub fn with(mut self, node: DocumentNode) -> Self {
        self.nodes.push(node);
        self
    }

    /// Writes one live edit into the model, or explains why it does not fit.
    ///
    /// A live edit names its target as `<node>:<property>=<value>`: the node id the edit addresses,
    /// the property name, and the value as text (the library coerces it to the property's declared
    /// kind on the way to the control). Nothing is guessed: a subject without a target, an unknown
    /// node, or an empty property name is `Unsupported` with the reason, which the caller reports as
    /// a no-op.
    fn apply_live(&mut self, edit: &Edit) -> Application {
        let subject = edit.subject();
        let Some((raw_node, rest)) = subject.split_once(':') else {
            return Application::Unsupported(format!(
                "{} does not name <node>:<property>=<value>",
                edit.render()
            ));
        };
        let Ok(raw_node) = raw_node.trim().parse::<u64>() else {
            return Application::Unsupported(format!(
                "{} names {raw_node:?}, which is not a node id",
                edit.render()
            ));
        };
        let Some((name, value)) = rest.split_once('=') else {
            return Application::Unsupported(format!(
                "{} does not name <node>:<property>=<value>",
                edit.render()
            ));
        };
        let name = name.trim();
        if name.is_empty() {
            return Application::Unsupported(format!("{} names no property", edit.render()));
        }
        let Some(node) = self
            .nodes
            .iter_mut()
            .find(|held| held.node.get() == raw_node)
        else {
            return Application::Unsupported(format!(
                "{} names node {raw_node}, which is not in the document",
                edit.render()
            ));
        };
        if node.set_property(name.to_owned(), value.to_owned()) {
            Application::Changed
        } else {
            Application::Unchanged
        }
    }
}

impl View for Document {
    fn build(&self) -> Node {
        let mut root = Node::new(self.root.as_str()).key("root");
        for node in &self.nodes {
            let mut child = Node::new(node.kind.as_str())
                .key(node.node.get().to_string())
                .prop("text", CapabilityValue::String(node.text.clone()));
            for (name, value) in &node.props {
                // `text` has its own field above; declaring it twice would be one value with two
                // owners, and the diff would report a change in the property it did not write.
                if name == "text" {
                    continue;
                }
                child = child.prop(name.as_str(), CapabilityValue::String(value.clone()));
            }
            root = root.child(child);
        }
        root
    }
}

/// What a mount created.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct MountReport {
    /// Controls the library created.
    pub widgets_created: usize,
    /// Patches the library could not carry out (a refused property, an unknown widget).
    pub issues: usize,
    /// The mounted engine's generation after the mount.
    pub generation: u64,
}

/// What an update applied.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct UpdateReport {
    /// Patches the diff emitted.
    pub patches: usize,
    /// Subtrees the diff had to replace.
    pub replaced_subtrees: usize,
    /// Children matched only by position.
    pub positional_matches: usize,
    /// The mounted engine's generation after the update.
    pub generation: u64,
    /// How many updates this session has applied.
    pub updates: u32,
}

/// What a classified edit batch made the live session do.
///
/// See the module docs: the variants are the three honest outcomes, and "classified live" is not by
/// itself a claim that anything was patched.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum Decision {
    /// The edited declaration was rebuilt and diffed onto the mounted tree.
    ///
    /// `report.patches` is the diff's count, not an incremental cost: the library rebuilt the whole
    /// declaration first ([`ViewEngine::update`] has no partial-door equivalent). The engine's own
    /// patch preservation is what keeps untouched controls, and therefore their focus and scroll,
    /// alive across it.
    ///
    /// The library applies those patches internally and returns only the diff, so a control that
    /// refuses a property name is not visible in this answer; a caller that needs that certainty
    /// reads the property back from the live control.
    Applied {
        /// What the library's diff reported.
        report: UpdateReport,
        /// Live edits that changed no value, or that the document does not model.
        untouched: Vec<String>,
    },
    /// No patch was claimed and the session cannot absorb the batch; build, then restart.
    RestartRequired {
        /// Why the live session cannot take it, and what has to happen instead.
        reason: String,
    },
    /// Nothing was patched because there was nothing to change.
    Noop {
        /// Why nothing changed.
        reason: String,
    },
}

impl Decision {
    /// The decision's name.
    pub fn name(&self) -> &'static str {
        match self {
            Self::Applied { .. } => "applied",
            Self::RestartRequired { .. } => "restart-required",
            Self::Noop { .. } => "noop",
        }
    }

    /// Whether the caller must build and restart before the session can show the edit.
    ///
    /// This answer is about the *session*, not about whether cargo ran here: nothing in this module
    /// starts a build.
    pub fn needs_cargo(&self) -> bool {
        matches!(self, Self::RestartRequired { .. })
    }

    /// The update report, when the batch was applied.
    pub fn report(&self) -> Option<&UpdateReport> {
        match self {
            Self::Applied { report, .. } => Some(report),
            _ => None,
        }
    }

    /// The reason, for the two outcomes that patched nothing.
    pub fn reason(&self) -> Option<&str> {
        match self {
            Self::RestartRequired { reason } | Self::Noop { reason } => Some(reason),
            Self::Applied { .. } => None,
        }
    }

    /// The decision in one line.
    pub fn render(&self) -> String {
        match self {
            Self::Applied { report, untouched } => {
                let mut line = format!(
                    "applied: {} patch(es) from one declaration rebuild, generation {}, {} update(s)",
                    report.patches, report.generation, report.updates
                );
                if !untouched.is_empty() {
                    line.push_str(&format!("; untouched: {}", untouched.join("; ")));
                }
                line
            }
            Self::RestartRequired { reason } => format!("restart required: {reason}"),
            Self::Noop { reason } => format!("noop: {reason}"),
        }
    }
}

/// Where the service is in its life.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum State {
    /// Not running.
    #[default]
    Stopped,
    /// Starting, not yet able to hold instances.
    Starting,
    /// Running.
    Running,
    /// Stopping: still holding what it must release.
    Stopping,
}

impl State {
    /// The state's name.
    pub fn name(&self) -> &'static str {
        match self {
            Self::Stopped => "stopped",
            Self::Starting => "starting",
            Self::Running => "running",
            Self::Stopping => "stopping",
        }
    }
}

/// A render instance of one node.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Instance {
    /// The node it renders.
    pub node: NodeId,
    /// Which build of it this is.
    pub generation: u32,
}

/// What stopping released.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Stopped {
    /// Whether a process was terminated.
    pub process: bool,
    /// The instances that were destroyed.
    pub instances: Vec<Instance>,
    /// The session that was released.
    pub session: Option<String>,
}

impl Stopped {
    /// The release in one line.
    pub fn render(&self) -> String {
        format!(
            "stopped: {} instance(s), process {}, session {}",
            self.instances.len(),
            if self.process { "terminated" } else { "none" },
            self.session.as_deref().unwrap_or("(none)")
        )
    }
}

/// The preview service.
///
/// This type owns a live [`ViewEngine`], so it is deliberately neither `Clone` nor `Debug`: there is
/// one engine per session and a duplicated service would be a second, unreachable one.
#[derive(Default)]
pub struct Preview {
    /// Where it is in its life.
    pub state: State,
    /// The session it owns.
    pub session: Option<String>,
    /// The instances it is holding.
    pub instances: Vec<Instance>,
    /// The child process it started, if any.
    pub process: Option<u32>,
    /// How many view updates the session has applied.
    pub updates: u32,
    /// The mounted engine's generation at the last mount or update.
    pub view_generation: u64,
    /// The live declarative engine, or `None` when nothing is mounted.
    engine: Option<ViewEngine>,
    /// The last document that mounted or updated successfully.
    ///
    /// Kept so a failed update can rebuild the previous tree on the same engine. The library's
    /// `update` installs the new declaration even when it reports `root_replaced`, so without this
    /// rollback every later update would keep comparing against the failed tree.
    mounted: Option<Document>,
    /// Every control id this session created, including ones a later update removed.
    ///
    /// Tracked because `ViewEngine` has no `Drop` that unregisters its controls: without this list,
    /// stopping after an update that removed a subtree would leave those controls mounted.
    view_ids: BTreeSet<ObjectId>,
    generations: BTreeMap<NodeId, u32>,
}

impl Preview {
    /// A stopped service.
    pub fn new() -> Self {
        Self::default()
    }

    /// Whether a declarative engine is mounted.
    pub fn has_live_engine(&self) -> bool {
        self.engine.is_some()
    }

    /// A snapshot of the mounted tree's identity map, or `None` when nothing is mounted.
    pub fn view_index(&self) -> Option<rust_widgets::view::TreeIndex> {
        self.engine.as_ref().map(ViewEngine::tree_index)
    }

    /// Mounts `document`, creating one live engine for the session.
    ///
    /// A mount while a view is already mounted replaces it: the previous controls are unregistered
    /// first, so a remount after a failure never leaves two trees mounted. If the root control
    /// cannot be created the engine is discarded and nothing is mounted, which is the honest
    /// "no live view" answer rather than a half-mounted tree.
    pub fn mount_view(
        &mut self,
        document: &Document,
        create: &dyn Fn(&Node) -> Option<ObjectId>,
    ) -> Result<MountReport, String> {
        if self.state != State::Running {
            return Err(format!(
                "the service is {}, so no view can be mounted",
                self.state.name()
            ));
        }
        self.release_engine();
        self.instances.clear();
        self.updates = 0;

        let created = RefCell::new(Vec::new());
        let tracked = |node: &Node| {
            let id = create(node);
            if let Some(id) = id.filter(|&id| id != 0) {
                created.borrow_mut().push(id);
            }
            id
        };
        let mut engine = ViewEngine::new();
        let report = engine.mount(document, &tracked);
        let created = created.into_inner();
        if report.widgets_created == 0 {
            for id in created {
                rust_widgets::widget::runtime::unregister(id);
            }
            return Err("the preview view could not be mounted: no control was created".to_owned());
        }
        self.view_ids.extend(created);
        self.view_generation = engine.generation();
        self.engine = Some(engine);
        self.mounted = Some(document.clone());
        for node in &document.nodes {
            self.install(node.node)?;
        }
        Ok(MountReport {
            widgets_created: report.widgets_created,
            issues: report.errors.len(),
            generation: self.view_generation,
        })
    }

    /// Applies the diff between the mounted tree and `document`.
    ///
    /// This is the unclassified primitive: it trusts that `document` is the tree the caller means
    /// to show. [`Self::apply_update`] is the classified door onto it, and the one a hot-update
    /// batch should use so a structural change is refused rather than patched by accident.
    ///
    /// A root kind change is refused rather than counted: a patch batch cannot replace a root, so
    /// the previous tree is still mounted and must be remounted. A control the caller could not
    /// create is also a failure, and the session keeps its engine so a later update can recover.
    pub fn update_view(
        &mut self,
        document: &Document,
        create: &dyn Fn(&Node) -> Option<ObjectId>,
    ) -> Result<UpdateReport, String> {
        if self.state != State::Running {
            return Err(format!(
                "the service is {}, so no view can be updated",
                self.state.name()
            ));
        }
        if self.engine.is_none() {
            return Err("no view is mounted, so there is nothing to update".to_owned());
        }
        let previous = self.mounted.clone();

        let created = RefCell::new(Vec::new());
        let failures = Cell::new(0usize);
        let tracked = |node: &Node| match create(node).filter(|&id| id != 0) {
            Some(id) => {
                created.borrow_mut().push(id);
                Some(id)
            }
            None => {
                failures.set(failures.get() + 1);
                None
            }
        };
        let report = self
            .engine
            .as_mut()
            .expect("the engine was checked above")
            .update(document, &tracked);
        self.view_ids.extend(created.into_inner());

        let failure = if report.root_replaced {
            Some(
                "the root's widget type changed; a patch batch cannot replace a root, so the view \
                 must be remounted"
                    .to_owned(),
            )
        } else if failures.get() > 0 {
            Some(format!(
                "{} control(s) could not be created; the mounted tree was only partly updated",
                failures.get()
            ))
        } else {
            None
        };
        if let Some(reason) = failure {
            // `update` installs the failed declaration even when it emitted no root patch, so
            // rebuild the last good document on the same engine before reporting the failure.
            if let Some(previous) = previous
                && let Err(rollback) = self.restore_document(&previous, create)
            {
                return Err(format!("{reason}; rollback also failed: {rollback}"));
            }
            return Err(reason);
        }

        self.updates = self.updates.saturating_add(1);
        self.mounted = Some(document.clone());
        self.view_generation = self
            .engine
            .as_ref()
            .expect("the engine was checked above")
            .generation();
        for node in &document.nodes {
            self.install(node.node)?;
        }
        Ok(UpdateReport {
            patches: report.patch_count(),
            replaced_subtrees: report.replaced_subtrees,
            positional_matches: report.positional_matches,
            generation: self.view_generation,
            updates: self.updates,
        })
    }

    /// Applies a classified edit batch to the live session.
    ///
    /// This is the door that connects [`hot_update::Updater`]'s classification to the mounted
    /// engine; [`Self::update_view`] is the unclassified primitive underneath it. The batch is
    /// decided as a unit, and the answer is a [`Decision`] rather than a patch count:
    ///
    /// * A rebuilding edit — an added or removed node, an added or removed binding, source text —
    ///   is [`Decision::RestartRequired`] and the session is not touched. The library's diff can
    ///   insert a node, but the declaration this session runs comes from generated code; patching
    ///   the live tree would show a tree the next build cannot reproduce, so no patch is claimed.
    /// * Live edits are written into a copy of the document and the copy is handed to the
    ///   library's update, which rebuilds the whole declaration and patches the difference. The
    ///   caller's document is replaced only when the update succeeded.
    /// * A live edit the document does not model, or one whose value is already the model's, is
    ///   reported in `untouched`; if that is the whole batch the answer is [`Decision::Noop`].
    /// * A live-classified batch the library still refuses (a changed root kind) becomes
    ///   [`Decision::RestartRequired`] carrying the library's reason. The session keeps its last
    ///   good declaration mounted, so it is still usable afterwards.
    pub fn apply_update(
        &mut self,
        update: &hot_update::Update,
        document: &mut Document,
        create: &dyn Fn(&Node) -> Option<ObjectId>,
    ) -> Result<Decision, String> {
        if self.state != State::Running {
            return Err(format!(
                "the service is {}, so no edit can be applied",
                self.state.name()
            ));
        }
        if self.engine.is_none() {
            return Err("no view is mounted, so no edit can be applied".to_owned());
        }

        let rebuilding: Vec<&Edit> = update
            .edits
            .iter()
            .filter(|edit| edit.kind().needs_cargo())
            .collect();
        if !rebuilding.is_empty() {
            let named: Vec<&str> = rebuilding.iter().map(|edit| edit.name()).collect();
            return Ok(Decision::RestartRequired {
                reason: format!(
                    "the batch's rebuilding edits ({}) are not patched into the live session: the \
                     library's update rebuilds and diffs one whole declaration, and the declaration \
                     this session runs comes from generated code, so the session must be restarted \
                     after the build",
                    named.join(", ")
                ),
            });
        }

        let mut next = document.clone();
        let mut untouched = Vec::new();
        let mut changed = Vec::new();
        for edit in &update.edits {
            match next.apply_live(edit) {
                Application::Changed => changed.push(edit.render()),
                Application::Unchanged => {
                    untouched.push(format!("{} is already the model's value", edit.render()));
                }
                Application::Unsupported(reason) => untouched.push(reason),
            }
        }
        if changed.is_empty() {
            return Ok(Decision::Noop {
                reason: if untouched.is_empty() {
                    "the batch carried no live edit".to_owned()
                } else {
                    format!(
                        "no live edit addresses the document: {}",
                        untouched.join("; ")
                    )
                },
            });
        }

        match self.update_view(&next, create) {
            Ok(report) => {
                *document = next;
                Ok(Decision::Applied { report, untouched })
            }
            // `update_view` rebuilt the last good declaration on the same engine before
            // returning, so the session is still usable; the reason says what the library refused.
            Err(reason) => Ok(Decision::RestartRequired {
                reason: format!("the view layer refused the change: {reason}"),
            }),
        }
    }

    /// How many of this session's controls are still mounted right now.
    ///
    /// This is a measurement, not a counter: each id the session created is asked of the runtime, so
    /// a control that was unregistered without being removed from the session's list is not counted
    /// as live. It is what the load driver (task T14.08) uses as its per-cycle live count.
    pub fn live_controls(&self) -> usize {
        self.view_ids
            .iter()
            .filter(|id| rust_widgets::widget::runtime::is_mounted(**id))
            .count()
    }

    /// The control ids this session created, in id order.
    ///
    /// Captured *before* a stop so a caller can ask the runtime afterwards whether each control is
    /// really gone: after the stop the session has forgotten them, and asking it then would answer
    /// zero whether or not something is still mounted.
    pub fn control_ids(&self) -> Vec<ObjectId> {
        self.view_ids.iter().copied().collect()
    }

    /// Captures the focused control as a [`state_keep::Capture`].
    ///
    /// Only focus is captured: it is the one live state the library exposes generically. Scroll has
    /// no library-wide read and is therefore absent, as [`state_keep::SCROLL_GAP`] explains.
    pub fn capture_state(&self) -> Capture {
        let Some(engine) = &self.engine else {
            return Capture::new();
        };
        state_keep::capture_focus(
            &engine.tree_index(),
            rust_widgets::widget::runtime::focused_widget(),
        )
    }

    /// Restores the captured focus onto controls whose node and kind still match.
    ///
    /// The returned outcomes are the ordinary [`state_keep::restore`] decisions, so a gone or
    /// retyped node is reported and nothing is focused for it.
    pub fn restore_state(&self, capture: &Capture) -> Result<Vec<FocusRestore>, String> {
        let Some(engine) = &self.engine else {
            return Err("no view is mounted, so there is nothing to restore into".to_owned());
        };
        let plan = state_keep::restore_focus(capture, &engine.tree_index());
        let mut outcomes = Vec::with_capacity(plan.len());
        for entry in plan {
            if let Some(id) = entry.target {
                rust_widgets::widget::runtime::focus_widget(id);
            }
            outcomes.push(entry);
        }
        Ok(outcomes)
    }

    /// The exact scroll-restore gap in the pinned library.
    pub fn scroll_gap() -> &'static str {
        state_keep::SCROLL_GAP
    }

    /// Rebuilds `document` on the mounted engine after a failed update.
    ///
    /// Reusing the same engine is what makes "the previous engine is still usable" true rather than
    /// merely "a new one can be made": the caller's next update addresses this engine's identity.
    fn restore_document(
        &mut self,
        document: &Document,
        create: &dyn Fn(&Node) -> Option<ObjectId>,
    ) -> Result<(), String> {
        // Drop every control the failed attempt left behind (and the previous tree's controls,
        // which the remount replaces) before building the last good document again.
        for id in std::mem::take(&mut self.view_ids) {
            rust_widgets::widget::runtime::unregister(id);
        }
        let Some(engine) = self.engine.as_mut() else {
            return Err("the engine is gone".to_owned());
        };
        let created = RefCell::new(Vec::new());
        let tracked = |node: &Node| {
            let id = create(node).filter(|&id| id != 0);
            if let Some(id) = id {
                created.borrow_mut().push(id);
            }
            id
        };
        let report = engine.mount(document, &tracked);
        let created = created.into_inner();
        self.view_ids.extend(created);
        if report.widgets_created == 0 {
            self.engine = None;
            self.mounted = None;
            return Err("the previous view could not be rebuilt".to_owned());
        }
        self.view_generation = engine.generation();
        self.instances.clear();
        self.mounted = Some(document.clone());
        for node in &document.nodes {
            self.install(node.node)?;
        }
        Ok(())
    }

    /// Unregisters every control this session created and drops the engine.
    fn release_engine(&mut self) {
        self.mounted = None;
        if let Some(engine) = self.engine.take() {
            for id in std::mem::take(&mut self.view_ids) {
                rust_widgets::widget::runtime::unregister(id);
            }
            drop(engine);
        } else {
            self.view_ids.clear();
        }
    }

    /// Starts a session, refusing a second one while the first is live.
    pub fn start(&mut self, session: impl Into<String>) -> Result<(), String> {
        match self.state {
            State::Stopped => {
                self.state = State::Starting;
                self.session = Some(session.into());
                Ok(())
            }
            other => Err(format!(
                "the service is {}, so a session cannot start",
                other.name()
            )),
        }
    }

    /// Moves a starting service to running.
    pub fn ready(&mut self) -> Result<(), String> {
        if self.state == State::Starting {
            self.state = State::Running;
            Ok(())
        } else {
            Err(format!(
                "the service is {}, not starting",
                self.state.name()
            ))
        }
    }

    /// Records the child process the preview runs in.
    pub fn spawn(&mut self, process: u32) -> Result<(), String> {
        if self.state != State::Running {
            return Err(format!(
                "the service is {}, so nothing can be spawned",
                self.state.name()
            ));
        }
        self.process = Some(process);
        Ok(())
    }

    /// Installs a render instance for a node, only while running.
    pub fn install(&mut self, node: NodeId) -> Result<Instance, String> {
        if self.state != State::Running {
            return Err(format!(
                "the service is {}, so no instance can be installed",
                self.state.name()
            ));
        }
        let generation = self.generations.entry(node).or_insert(0);
        let instance = Instance {
            node,
            generation: *generation,
        };
        match self.instances.iter_mut().find(|held| held.node == node) {
            Some(held) => *held = instance,
            None => self.instances.push(instance),
        }
        Ok(instance)
    }

    /// Rebuilds a node's instance as a new generation.
    pub fn rebuild(&mut self, node: NodeId) -> Result<Instance, String> {
        let generation = self.generations.entry(node).or_insert(0);
        *generation += 1;
        self.install(node)
    }

    /// Stops the service, releasing the process and the instances.
    pub fn stop(&mut self) -> Result<Stopped, String> {
        match self.state {
            State::Running | State::Starting => {
                self.state = State::Stopping;
                let released = Stopped {
                    process: self.process.is_some(),
                    instances: std::mem::take(&mut self.instances),
                    session: self.session.clone(),
                };
                self.process = None;
                self.release_engine();
                Ok(released)
            }
            other => Err(format!(
                "the service is {}, so it cannot stop",
                other.name()
            )),
        }
    }

    /// Finishes a stop, releasing the session.
    pub fn finish_stop(&mut self) -> Result<(), String> {
        if self.state == State::Stopping {
            self.state = State::Stopped;
            self.session = None;
            Ok(())
        } else {
            Err(format!(
                "the service is {}, not stopping",
                self.state.name()
            ))
        }
    }

    /// Whether nothing is left over: no engine, no controls, no instances, no process and no
    /// session.
    pub fn is_clean(&self) -> bool {
        self.instances.is_empty()
            && self.process.is_none()
            && self.session.is_none()
            && self.engine.is_none()
            && self.mounted.is_none()
            && self.view_ids.is_empty()
    }

    /// The service in one line per fact.
    pub fn render(&self) -> Vec<String> {
        let mut lines = vec![
            format!("state: {}", self.state.name()),
            format!("session: {}", self.session.as_deref().unwrap_or("(none)")),
            format!(
                "process: {}",
                self.process
                    .map(|process| process.to_string())
                    .unwrap_or_else(|| "(none)".to_owned())
            ),
        ];
        lines.push(format!("instances: {}", self.instances.len()));
        for instance in &self.instances {
            lines.push(format!(
                "  node {} (generation {})",
                instance.node.get(),
                instance.generation
            ));
        }
        lines.push(format!(
            "engine: {}",
            if self.engine.is_some() {
                "mounted"
            } else {
                "(none)"
            }
        ));
        lines.push(format!("updates: {}", self.updates));
        lines.push(format!("view generation: {}", self.view_generation));
        lines
    }
}

