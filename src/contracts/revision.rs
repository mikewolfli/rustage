//! Versions and staleness: contract **C-VERSION**.
//!
//! The designer holds several things that change at different rates: the model (every edit), the
//! project file format (rarely, through migration), the generator (per release) and the widget
//! dependency (per pinned revision). Results computed from one of them — diagnostics, generated
//! code, a source map, a preview — are only meaningful together with the versions they came from.
//!
//! This module gives them one shape, [`VersionStamp`], so that "current" always means "stamped
//! with the model revision the store is at right now" and everything else can be labelled rather
//! than shown as if it were fresh (whitepaper §17.6: stale diagnostics are marked stale instead of
//! being presented as current errors).
//!
//! The dependency revision is deliberately **not** repeated here: it lives in exactly one place,
//! `crate::probe::DEPENDENCY_REVISION`, and is tied to `Cargo.lock` by that module's drift test.
//! A second copy of it would be a second source of truth for the one fact this project most needs
//! to stay unambiguous.

use std::fmt;

/// How many times the model has been changed. Starts at [`Revision::INITIAL`].
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Default)]
pub struct Revision(u64);

impl Revision {
    /// The revision a document has before anything is applied.
    pub const INITIAL: Self = Self(0);

    /// Rebuilds a revision from the number it was written as.
    pub const fn from_raw(value: u64) -> Self {
        Self(value)
    }

    /// The number this revision is written as.
    pub const fn get(self) -> u64 {
        self.0
    }

    /// The next revision. Only the store's apply path may use this, and only once per change set.
    pub const fn next(self) -> Self {
        Self(self.0 + 1)
    }
}

impl fmt::Display for Revision {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "r{}", self.0)
    }
}

/// The project-file format version. A file without it cannot be migrated, so it is mandatory
/// (decision `Q6`).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub struct FormatVersion(u32);

impl FormatVersion {
    /// The format this build writes.
    pub const CURRENT: Self = Self(1);

    /// Rebuilds a version from the number it was written as.
    pub const fn from_raw(value: u32) -> Self {
        Self(value)
    }

    /// The number this version is written as.
    pub const fn get(self) -> u32 {
        self.0
    }
}

impl fmt::Display for FormatVersion {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "format v{}", self.0)
    }
}

/// The generator that produced an artifact. Compared so that "generated by whom" is answerable.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub struct GeneratorVersion {
    pub major: u32,
    pub minor: u32,
    pub patch: u32,
}

impl GeneratorVersion {
    /// The generator this build contains. Bumped whenever generation output can change.
    pub const CURRENT: Self = Self {
        major: 0,
        minor: 1,
        patch: 0,
    };

    /// An explicit version, for tests and for reading a stamp back from a file.
    pub const fn new(major: u32, minor: u32, patch: u32) -> Self {
        Self {
            major,
            minor,
            patch,
        }
    }
}

impl fmt::Display for GeneratorVersion {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "generator {}.{}.{}",
            self.major, self.minor, self.patch
        )
    }
}

/// What an artifact was produced from.
///
/// Every artifact that outlives a single call carries one: diagnostics, generated files, source
/// maps and preview snapshots. Comparison is by model revision, because that is the thing that
/// decides whether a result still describes the document in front of the user.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct VersionStamp {
    pub model: Revision,
    pub format: FormatVersion,
    pub generator: GeneratorVersion,
}

impl VersionStamp {
    /// A stamp for the given model revision under this build's format and generator versions.
    pub const fn current(model: Revision) -> Self {
        Self {
            model,
            format: FormatVersion::CURRENT,
            generator: GeneratorVersion::CURRENT,
        }
    }

    /// Whether the artifact this stamp belongs to still describes `current`.
    pub fn is_current_for(&self, current: Revision) -> bool {
        self.model == current
    }

    /// Labels the artifact against the model revision the user is looking at now.
    pub fn staleness(&self, current: Revision) -> Staleness {
        Staleness::between(self.model, current)
    }
}

/// Whether a result describes the model the user is looking at.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Staleness {
    /// Computed from the current revision.
    Current,
    /// Computed from an older revision: it may be shown, but only labelled as outdated.
    Stale {
        computed_at: Revision,
        current: Revision,
    },
}

impl Staleness {
    /// Compares the revision an artifact was computed at with the current one.
    pub fn between(computed_at: Revision, current: Revision) -> Self {
        if computed_at == current {
            Self::Current
        } else {
            Self::Stale {
                computed_at,
                current,
            }
        }
    }

    /// Whether the artifact is up to date. Callers that must not show outdated results ask this
    /// rather than comparing revisions themselves.
    pub fn is_current(self) -> bool {
        matches!(self, Self::Current)
    }
}

impl fmt::Display for Staleness {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Current => write!(formatter, "current"),
            Self::Stale {
                computed_at,
                current,
            } => {
                write!(
                    formatter,
                    "stale: computed at {computed_at}, document is at {current}"
                )
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{FormatVersion, GeneratorVersion, Revision, Staleness, VersionStamp};

    #[test]
    fn a_revision_advances_by_one_and_displays_itself() {
        let start = Revision::INITIAL;

        assert_eq!(start.get(), 0);
        assert_eq!(start.next().get(), 1);
        assert_eq!(start.next().next(), Revision::from_raw(2));
        assert_eq!(start.to_string(), "r0");
    }

    #[test]
    fn a_stamp_is_current_only_for_its_own_revision() {
        let stamp = VersionStamp::current(Revision::from_raw(4));

        assert!(stamp.is_current_for(Revision::from_raw(4)));
        assert!(!stamp.is_current_for(Revision::from_raw(5)));
        assert_eq!(stamp.format, FormatVersion::CURRENT);
        assert_eq!(stamp.generator, GeneratorVersion::CURRENT);
    }

    #[test]
    fn staleness_names_both_revisions_instead_of_just_failing() {
        let stale = VersionStamp::current(Revision::from_raw(2)).staleness(Revision::from_raw(7));

        assert!(!stale.is_current());
        assert_eq!(
            stale,
            Staleness::Stale {
                computed_at: Revision::from_raw(2),
                current: Revision::from_raw(7)
            },
        );
        assert!(stale.to_string().contains("computed at r2"));
        assert!(stale.to_string().contains("document is at r7"));
    }

    #[test]
    fn matching_revisions_report_current() {
        let revision = Revision::from_raw(3);

        assert_eq!(Staleness::between(revision, revision), Staleness::Current);
        assert!(Staleness::between(revision, revision).is_current());
    }

    #[test]
    fn versions_display_what_they_are() {
        assert_eq!(FormatVersion::CURRENT.to_string(), "format v1");
        assert_eq!(
            GeneratorVersion::new(1, 2, 3).to_string(),
            "generator 1.2.3"
        );
    }
}
