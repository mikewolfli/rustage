//! The probe report: what was run, against which revision, and what came back.
//!
//! Two renderings of one dataset: [`ProbeReport::render_text`] for a human reading a terminal, and
//! [`ProbeReport::render_json`] for a tool consuming the artifact. Both are deterministic, so a
//! report committed as evidence can be regenerated and compared byte for byte — the same
//! regenerate-and-compare discipline the resource tooling uses, applied here so "the probes passed"
//! is a claim someone else can reproduce.

use std::fmt::Write;

use super::{DEPENDENCY_CRATE, DEPENDENCY_REVISION, DEPENDENCY_VERSION, ProbeOutcome, ProbeResult};

/// The outcome of one probe run, with the environment it ran in.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProbeReport {
    /// The rustage build the probes ran in.
    pub rustage_version: String,
    /// `std::env::consts::OS` of the host.
    pub host_os: String,
    /// `std::env::consts::ARCH` of the host.
    pub host_arch: String,
    /// The dependency crate name.
    pub dependency_crate: String,
    /// The pinned dependency version.
    pub dependency_version: String,
    /// The pinned dependency revision.
    pub dependency_revision: String,
    /// Every probe's result, in run order.
    pub results: Vec<ProbeResult>,
}

impl ProbeReport {
    /// Builds a report from a probe run, filling in the environment from the running process.
    pub fn new(results: Vec<ProbeResult>) -> Self {
        Self {
            rustage_version: env!("CARGO_PKG_VERSION").to_string(),
            host_os: std::env::consts::OS.to_string(),
            host_arch: std::env::consts::ARCH.to_string(),
            dependency_crate: DEPENDENCY_CRATE.to_string(),
            dependency_version: DEPENDENCY_VERSION.to_string(),
            dependency_revision: DEPENDENCY_REVISION.to_string(),
            results,
        }
    }

    /// Runs every probe and wraps the results in a report.
    pub fn run() -> Self {
        Self::new(super::run_all())
    }

    /// Counts of `(verified, gap)`.
    pub fn counts(&self) -> (usize, usize) {
        let mut verified = 0;
        let mut gap = 0;
        for result in &self.results {
            match result.outcome {
                ProbeOutcome::Verified => verified += 1,
                ProbeOutcome::Gap(_) => gap += 1,
            }
        }
        (verified, gap)
    }

    /// Counts of `(verified, gap)` restricted to one family.
    pub fn family_counts(&self, family: super::ApiFamily) -> (usize, usize) {
        let mut verified = 0;
        let mut gap = 0;
        for result in self.results.iter().filter(|result| result.family == family) {
            match result.outcome {
                ProbeOutcome::Verified => verified += 1,
                ProbeOutcome::Gap(_) => gap += 1,
            }
        }
        (verified, gap)
    }

    /// Whether every probe proved its contract.
    ///
    /// A probe that did not run is not a pass (principle #24/#26), so anything other than
    /// [`ProbeOutcome::Verified`] makes the report unclean.
    pub fn is_clean(&self) -> bool {
        self.results
            .iter()
            .all(|result| result.outcome.is_verified())
    }

    /// The human-readable rendering, one line per probe.
    pub fn render_text(&self) -> String {
        let mut out = String::new();
        let _ = writeln!(
            out,
            "rustage api probes ({} {} @ {})",
            self.dependency_crate,
            self.dependency_version,
            &self.dependency_revision[..12.min(self.dependency_revision.len())]
        );
        let _ = writeln!(
            out,
            "host {}/{} · rustage {}",
            self.host_os, self.host_arch, self.rustage_version
        );
        for result in &self.results {
            let _ = write!(
                out,
                "{:<11}{:<9}{}",
                result.family.as_str(),
                result.outcome.as_str(),
                result.api
            );
            if let Some(reason) = result.outcome.reason() {
                let _ = write!(out, "  — {reason}");
            }
            out.push('\n');
        }
        let per_family: Vec<String> = super::ApiFamily::ALL
            .iter()
            .map(|family| {
                let (verified, gap) = self.family_counts(*family);
                format!("{} {verified}/{}", family.as_str(), verified + gap)
            })
            .collect();
        let _ = writeln!(out, "per family: {}", per_family.join(", "));
        let (verified, gap) = self.counts();
        let _ = writeln!(out, "summary: {verified} verified, {gap} gap");
        out
    }

    /// The machine-readable rendering: stable JSON, regenerated byte for byte.
    pub fn render_json(&self) -> String {
        let mut out = String::new();
        out.push_str("{\n");
        let _ = writeln!(
            out,
            "  \"rustage\": {},",
            json_string(&self.rustage_version)
        );
        let _ = writeln!(
            out,
            "  \"host\": {{ \"os\": {}, \"arch\": {} }},",
            json_string(&self.host_os),
            json_string(&self.host_arch)
        );
        let _ = writeln!(
            out,
            "  \"dependency\": {{ \"crate\": {}, \"version\": {}, \"revision\": {} }},",
            json_string(&self.dependency_crate),
            json_string(&self.dependency_version),
            json_string(&self.dependency_revision)
        );
        let (verified, gap) = self.counts();
        let _ = writeln!(
            out,
            "  \"summary\": {{ \"verified\": {verified}, \"gap\": {gap} }},"
        );
        out.push_str("  \"probes\": [\n");
        for (index, result) in self.results.iter().enumerate() {
            out.push_str("    {\n");
            let _ = writeln!(
                out,
                "      \"family\": {},",
                json_string(result.family.as_str())
            );
            let _ = writeln!(out, "      \"api\": {},", json_string(result.api));
            let _ = writeln!(
                out,
                "      \"outcome\": {},",
                json_string(result.outcome.as_str())
            );
            match result.outcome.reason() {
                Some(reason) => {
                    let _ = writeln!(out, "      \"reason\": {},", json_string(reason));
                }
                None => out.push_str("      \"reason\": null,\n"),
            }
            out.push_str("      \"notes\": [");
            if result.notes.is_empty() {
                out.push(']');
            } else {
                out.push('\n');
                for (note_index, note) in result.notes.iter().enumerate() {
                    let comma = if note_index + 1 == result.notes.len() {
                        ""
                    } else {
                        ","
                    };
                    let _ = writeln!(out, "        {}{comma}", json_string(note));
                }
                out.push_str("      ]");
            }
            out.push('\n');
            let comma = if index + 1 == self.results.len() {
                ""
            } else {
                ","
            };
            let _ = writeln!(out, "    }}{comma}");
        }
        out.push_str("  ]\n}\n");
        out
    }
}

/// Escapes a string as a JSON literal.
///
/// `pub(crate)` because the host readiness report and the project file render their own artifacts
/// and must not grow a second escaper: two implementations would eventually disagree about which
/// characters are legal inside a literal, and one of the two artifacts would be the one that is
/// wrong (principle #35). The rule itself lives next to the writer that owns it,
/// [`crate::project::record::json::escape_string`].
pub(crate) fn json_string(value: &str) -> String {
    crate::project::record::json::escape_string(value)
}

#[cfg(test)]
mod tests {
    use super::{ProbeReport, json_string};
    use crate::probe::{ApiFamily, ProbeResult};

    #[test]
    fn json_string_escapes_what_json_requires() {
        assert_eq!(json_string("plain"), "\"plain\"");
        assert_eq!(json_string("a\"b"), "\"a\\\"b\"");
        assert_eq!(json_string("a\\b"), "\"a\\\\b\"");
        assert_eq!(json_string("line\nbreak\ttab"), "\"line\\nbreak\\ttab\"");
        assert_eq!(json_string("\u{01}"), "\"\\u0001\"");
        // Non-ASCII passes through as UTF-8 rather than being escaped.
        assert_eq!(json_string("图标"), "\"图标\"");
    }

    #[test]
    fn json_render_is_deterministic_and_well_shaped() {
        let report = ProbeReport::new(vec![
            ProbeResult::verified(ApiFamily::Layout, "layout::A", vec!["a -> 1".to_string()]),
            ProbeResult::gap(ApiFamily::Event, "event::B", "expected 1, saw 2"),
        ]);
        let first = report.render_json();
        let second = report.render_json();
        assert_eq!(first, second, "the same report must render byte for byte");
        assert!(first.starts_with("{\n"));
        assert!(first.ends_with("]\n}\n"));
        assert!(first.contains("\"verified\": 1"));
        assert!(first.contains("\"gap\": 1"));
        assert!(first.contains("\"reason\": \"expected 1, saw 2\""));
        assert!(first.contains("\"reason\": null"));
    }

    #[test]
    fn a_gap_is_not_clean() {
        let clean = ProbeReport::new(vec![ProbeResult::verified(
            ApiFamily::Layout,
            "layout::A",
            Vec::new(),
        )]);
        assert!(clean.is_clean());

        let gap = ProbeReport::new(vec![ProbeResult::gap(ApiFamily::Layout, "layout::A", "no")]);
        assert!(!gap.is_clean());
        assert_eq!(gap.counts(), (0, 1));
    }

    #[test]
    fn every_family_has_at_least_one_probe() {
        let report = ProbeReport::run();
        for family in ApiFamily::ALL {
            assert!(
                report.results.iter().any(|result| result.family == family),
                "no probe covered the {} family",
                family.as_str()
            );
        }
    }

    /// Keeps [`DEPENDENCY_REVISION`](crate::probe::DEPENDENCY_REVISION) and the version constant
    /// honest against the lockfile that actually pins the dependency.
    ///
    /// The report prints a revision. If that revision were only a hand-typed string, it could name
    /// a commit the build never used — "stale result presented as current", the failure principle
    /// #22 forbids. This test is the gate that makes the constant trustworthy.
    #[test]
    fn recorded_revision_matches_the_lockfile() {
        let lock = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/Cargo.lock"))
            .expect("Cargo.lock is committed and readable next to Cargo.toml");
        let (version, revision) = rust_widgets_lock_entry(&lock);
        assert_eq!(
            version,
            crate::probe::DEPENDENCY_VERSION,
            "the recorded dependency version drifted from Cargo.lock"
        );
        assert_eq!(
            revision,
            crate::probe::DEPENDENCY_REVISION,
            "the recorded dependency revision drifted from Cargo.lock"
        );
    }

    /// Extracts `(version, git revision)` for the `rust_widgets` package from a `Cargo.lock`.
    ///
    /// Deliberately a tiny scanner rather than a TOML dependency: the lockfile format for this one
    /// query is fixed, and pulling a parser in to read two lines would be the "shared abstraction
    /// with no real benefit" principle #38 warns about.
    fn rust_widgets_lock_entry(lock: &str) -> (String, String) {
        let mut in_package = false;
        let mut version = None;
        let mut revision = None;
        for line in lock.lines() {
            let line = line.trim();
            if line.starts_with("[[package]]") {
                if in_package {
                    break;
                }
                in_package = false;
                continue;
            }
            if line == "name = \"rust_widgets\"" {
                in_package = true;
                continue;
            }
            if !in_package {
                continue;
            }
            if let Some(rest) = line.strip_prefix("version = ") {
                version = Some(rest.trim_matches('"').to_string());
            }
            if let Some(rest) = line.strip_prefix("source = ") {
                let source = rest.trim_matches('"');
                if let Some((_, sha)) = source.rsplit_once('#') {
                    revision = Some(sha.to_string());
                }
            }
        }
        (
            version.expect("rust_widgets must have a version in Cargo.lock"),
            revision.expect("rust_widgets must be a git dependency with a revision"),
        )
    }
}
